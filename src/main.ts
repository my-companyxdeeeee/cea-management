import Fastify from 'fastify';
import jwt from '@fastify/jwt';
import sensible from '@fastify/sensible';
import { env } from './infrastructure/config/env.js';
import { schedulingRoutes } from './modules/scheduling/interfaces/http/routes.js';
import { identityRoutes } from './modules/identity/interfaces/http/routes.js';
import { studentRoutes } from './modules/students/interfaces/http/routes.js';
import { fleetRoutes } from './modules/fleet/interfaces/http/routes.js';
import { instructorRoutes } from './modules/instructors/interfaces/http/routes.js';
import { financeRoutes } from './modules/finance/interfaces/http/routes.js';
import { runtRoutes } from './modules/students/interfaces/http/runt-routes.js';
import { fleetAlertRoutes } from './modules/fleet/interfaces/http/alert-routes.js';
import { progressRoutes } from './modules/students/interfaces/http/progress-routes.js';
const app = Fastify({ logger: true });
await app.register(sensible);
await app.register(jwt, { secret: env.JWT_SECRET });
app.decorate('authenticate', async (request: any) => request.jwtVerify());
app.get('/health', async () => ({ status: 'ok' }));
await app.register(identityRoutes, { prefix: '/api/v1' });
await app.register(studentRoutes, { prefix: '/api/v1' });
await app.register(fleetRoutes, { prefix: '/api/v1' });
await app.register(instructorRoutes, { prefix: '/api/v1' });
await app.register(financeRoutes, { prefix: '/api/v1' });
await app.register(runtRoutes, { prefix: '/api/v1' });
await app.register(fleetAlertRoutes, { prefix: '/api/v1' });
await app.register(schedulingRoutes, { prefix: '/api/v1' });
await app.register(progressRoutes, { prefix: '/api/v1' });
await app.listen({ port: env.PORT, host: '0.0.0.0' });

